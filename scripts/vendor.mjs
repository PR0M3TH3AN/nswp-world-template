// For maintainers of the template: copies the NSWP library, SDK and command-line
// tool from a sibling checkout of the NSWP repository, and records exactly what
// was taken. People using the template never need to run this.
//
//   npm run vendor          rebuild vendor/nswp/ from ../Nostr-Spatial-Web-Protocol--NSWP-
//   npm run vendor:check    verify vendor/ still matches vendor/integrity.json
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = join(root, "vendor", "integrity.json");
const out = join(root, "vendor", "nswp");
const sha256 = (path) => createHash("sha256").update(readFileSync(path)).digest("hex");

function listFiles(dir, base = dir) {
  return readdirSync(dir)
    .flatMap((name) => {
      const p = join(dir, name);
      return statSync(p).isDirectory() ? listFiles(p, base) : [relative(base, p)];
    })
    .sort();
}
const hashDir = (dir) => Object.fromEntries(listFiles(dir).map((f) => [f, sha256(join(dir, f))]));

if (process.argv.includes("--check")) {
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const actual = hashDir(out);
  const bad = [...new Set([...Object.keys(actual), ...Object.keys(manifest.files)])].filter((f) => actual[f] !== manifest.files[f]);
  for (const f of bad) console.error(`MISMATCH vendor/nswp/${f}`);
  if (bad.length) process.exit(1);
  console.log(`vendor ok: ${Object.keys(actual).length} files match integrity.json (NSWP ${manifest.source.commit.slice(0, 7)})`);
  process.exit(0);
}

const repo = join(root, "..", "Nostr-Spatial-Web-Protocol--NSWP-");
const git = (...args) => execFileSync("git", ["-C", repo, ...args], { encoding: "utf8" }).trim();
const dirty = git("status", "--porcelain") !== "";
if (dirty && !process.argv.includes("--allow-dirty")) throw new Error(`${repo} has uncommitted changes; vendor only from a clean checkout`);
const esbuild = join(repo, "node_modules", ".bin", "esbuild");
const tsc = join(repo, "node_modules", ".bin", "tsc");
if (!existsSync(esbuild)) throw new Error(`run npm install in ${repo} first`);
const run = (bin, args) => execFileSync(bin, args, { stdio: "inherit", cwd: repo });

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const common = ["--bundle", "--format=esm", "--target=es2022", "--legal-comments=inline", "--log-level=warning"];
// The library: events, manifests, portals, arrival, layouts.
run(esbuild, ["packages/core/src/index.ts", ...common, `--outfile=${join(out, "nswp-core.js")}`]);
run(tsc, ["-p", "packages/core", "--emitDeclarationOnly", "--declaration", "--outDir", join(out, "types")]);
// The world-side SDK, as entry points that share their code. The
// library and three.js stay outside, so a world's own build supplies one copy.
run(esbuild, [
  "index=packages/sdk/src/index.ts",
  "three=packages/sdk/src/three.ts",
  "home=packages/sdk/src/home.ts",
  "ui=packages/sdk/src/ui.ts",
  // A terminal on the owner's own computer, for a world they are building. Fetched only when they bring one.
  "terminal=packages/sdk/src/terminal.ts",
  ...common,
  "--splitting",
  "--chunk-names=shared-[hash]",
  "--external:@nswp/core",
  "--external:three",
  `--outdir=${join(out, "sdk")}`,
]);
run(tsc, ["-p", "packages/sdk", "--noEmit", "false", "--emitDeclarationOnly", "--declaration", "--rootDir", "packages/sdk/src", "--outDir", join(out, "sdk-types")]);
// The command-line tool, for `check` and `publish`.
run(esbuild, ["packages/cli/src/index.ts", ...common, "--platform=node", `--outfile=${join(out, "nswp-cli.js")}`]);

// Its licence, and the notices for the libraries built into these files, travel with them.
for (const name of ["LICENSE", "THIRD-PARTY-NOTICES.md"]) cpSync(join(repo, name), join(out, name));
// The sounds every world starts with: recorded cues, a room's hum and a piece of music, with a note of where each came from.
cpSync(join(repo, "packages", "sdk", "sounds"), join(out, "sounds"), { recursive: true });

const version = JSON.parse(readFileSync(join(repo, "packages/core/package.json"), "utf8")).version;
const source = { repository: git("remote", "get-url", "origin"), commit: git("rev-parse", "HEAD"), dirty };
writeFileSync(manifestPath, `${JSON.stringify({ note: "Generated by scripts/vendor.mjs. Do not edit by hand.", version, license: "MIT", source, files: hashDir(out) }, null, 2)}\n`);
console.log(`vendored NSWP ${version} @ ${source.commit.slice(0, 7)}${dirty ? " (uncommitted changes!)" : ""}: ${Object.keys(hashDir(out)).length} files`);
